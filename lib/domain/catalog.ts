/** The shared check for privacy and terms pages nobody has read yet. */
const NOT_CHECKED: Check = ["unknown", "unchecked", "Privacy and terms pages not checked yet"];

/** A source page Anchored read, labelled by its address without the scheme. */
function readAt(url: string): Tool["source"] {
  return { url, label: url.replace(/^https?:\/\/(www\.)?/, "") };
}

/** A source with no link to keep, such as a sales video or a third-party summary. */
function citedAs(label: string): Tool["source"] {
  return { url: null, label };
}

