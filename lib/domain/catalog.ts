/** Return the catalog tool with `id`, or `undefined` if none has it. */
export function toolById(id: string): Tool | undefined {
  return TOOLS.find((tool) => tool.id === id);
}

/** Display name with the maker in front, unless the name already says it ("Square Marketing", "Jobber AI Receptionist"). */
export function toolName(tool: Tool): string {
  return normalizeName(tool.name).includes(normalizeName(tool.maker)) ? tool.name : `${tool.maker} ${tool.name}`;
}

/** Lower-case a software name and drop everything but letters and digits, so "QuickBooks Online" and "quickbooks-online" compare equal. */
export function normalizeName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]/g, "");
}

/** Whether a tool is built for this kind of business, or for any business. */
export function fitsTrade(tool: Tool, tradeKey: TradeKey): boolean {
  return tool.for.includes(tradeKey) || tool.for.includes("any");
}
