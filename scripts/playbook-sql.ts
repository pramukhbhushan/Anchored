import { hashtagId } from "../lib/domain/playbook";
import { PLAYBOOK_SEED } from "../lib/domain/playbook-seed";

// =============================================================================
// Module Overview
// =============================================================================
// Prints the SQL that creates the post playbook tables and upserts every row of
// `PLAYBOOK_SEED`, so the database and the in-memory store hold the same rows.
// Run `npm run playbook:sql > supabase/migrations/<timestamp>_post_playbook.sql`
// for a new migration after editing the seed. The upserts make it safe to run
// again in the Supabase SQL editor.

/** Quote `value` as a SQL string literal. */
function lit(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

/** Write `values` as a SQL text array. */
function arr(values: readonly string[]): string {
  return values.length === 0 ? "'{}'::text[]" : `array[${values.map(lit).join(", ")}]::text[]`;
}

/** Build one upsert for `table` that overwrites every column but `id` on conflict. */
function upsert(table: string, columns: readonly string[], rows: readonly string[][]): string {
  const updates = columns.filter((c) => c !== "id").map((c) => `${c} = excluded.${c}`);
  return [
    `insert into ${table} (${columns.join(", ")}) values`,
    rows.map((r) => `  (${r.join(", ")})`).join(",\n"),
    `on conflict (id) do update set ${updates.join(", ")}, updated_at = now();`,
  ].join("\n");
}

const SCHEMA = `-- =============================================================================
-- Post playbook
-- =============================================================================
-- Proven post formats, hooks and hashtags for each niche and platform, which the
-- Marketing agent writes Instagram, Facebook and LinkedIn captions from. These
-- are shared reference rows, not any session's data: every visitor may read
-- them, and only the service role writes them. Generated by
-- \`npm run playbook:sql\` from \`lib/domain/playbook-seed.ts\`; edit the seed
-- there and add a new migration rather than changing this one.

create table if not exists post_formats (
  id text primary key,
  name text not null,
  niches text[] not null,
  platforms text[] not null,
  media text not null check (media in ('single', 'carousel', 'either')),
  min_photos integer not null check (min_photos >= 1),
  max_photos integer not null check (max_photos >= min_photos),
  why text not null,
  structure text[] not null,
  photo_ideas text[] not null,
  cues text[] not null default '{}',
  updated_at timestamptz not null default now()
);

create table if not exists post_hooks (
  id text primary key,
  text text not null,
  niches text[] not null,
  platforms text[] not null,
  formats text[] not null default '{}',
  updated_at timestamptz not null default now()
);

create table if not exists post_hashtags (
  id text primary key,
  tag text not null check (tag ~ '^#[A-Za-z0-9_]+$'),
  niches text[] not null,
  platforms text[] not null,
  trade text,
  updated_at timestamptz not null default now()
);

alter table post_formats enable row level security;
alter table post_hooks enable row level security;
alter table post_hashtags enable row level security;
drop policy if exists post_formats_read on post_formats;
drop policy if exists post_hooks_read on post_hooks;
drop policy if exists post_hashtags_read on post_hashtags;
create policy post_formats_read on post_formats for select to anon, authenticated using (true);
create policy post_hooks_read on post_hooks for select to anon, authenticated using (true);
create policy post_hashtags_read on post_hashtags for select to anon, authenticated using (true);
`;

const { formats, hooks, hashtags } = PLAYBOOK_SEED;

const sql = [
  SCHEMA,
  upsert(
    "post_formats",
    ["id", "name", "niches", "platforms", "media", "min_photos", "max_photos", "why", "structure", "photo_ideas", "cues"],
    formats.map((f) => [lit(f.id), lit(f.name), arr(f.niches), arr(f.platforms), lit(f.media), String(f.minPhotos), String(f.maxPhotos), lit(f.why), arr(f.structure), arr(f.photoIdeas), arr(f.cues)]),
  ),
  "",
  upsert("post_hooks", ["id", "text", "niches", "platforms", "formats"], hooks.map((h) => [lit(h.id), lit(h.text), arr(h.niches), arr(h.platforms), arr(h.formats)])),
  "",
  upsert(
    "post_hashtags",
    ["id", "tag", "niches", "platforms", "trade"],
    hashtags.map((h) => [lit(hashtagId(h)), lit(h.tag), arr(h.niches), arr(h.platforms), h.trade === null ? "null" : lit(h.trade)]),
  ),
  "",
].join("\n");

process.stdout.write(sql);
